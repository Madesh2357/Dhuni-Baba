import { expect, test } from '@playwright/test'
import { enterMyDetails, mockGeocoder } from './helpers'

test.beforeEach(async ({ page }) => {
  await mockGeocoder(page)
})

test('birth details → Kundli with readings, chart and dashas', async ({ page }) => {
  await enterMyDetails(page)
  await expect(page.getByRole('heading', { name: "Baba's readings" })).toBeVisible()
  await expect(page.getByText('From your Lagna in Simha (Leo)')).toBeVisible()
  await expect(page.getByRole('img', { name: /Birth chart/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Vimshottari dasha' })).toBeVisible()
  // No sideways scrolling on any screen size.
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(0)
})

test('a share link reopens the same reading without saving it', async ({ page, context }) => {
  await enterMyDetails(page)
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.evaluate(() => Object.defineProperty(navigator, 'share', { value: undefined }))
  await page.getByRole('button', { name: 'Share this reading' }).click()
  await expect(page.getByText('Link copied')).toBeVisible()
  const link = await page.evaluate(() => navigator.clipboard.readText())
  expect(link).toMatch(/\/share#v1\./)

  const fresh = await context.newPage()
  await fresh.goto(link)
  await expect(fresh.getByText('A reading shared with you')).toBeVisible()
  await expect(fresh.getByRole('heading', { name: 'Namaste, Zero.' })).toBeVisible()
  expect(await fresh.evaluate(() => sessionStorage.length)).toBe(0)
})

test('a broken share link explains itself', async ({ page }) => {
  await page.goto('/share#v1.garbage')
  await expect(page.getByRole('heading', { name: 'This link looks broken' })).toBeVisible()
})

test('Guna Milan compatibility', async ({ page }) => {
  await enterMyDetails(page)
  await page.goto('/match')
  await page.getByLabel('Partner’s name').fill('Partner')
  await page.getByLabel('Date of birth').fill('1996-02-14')
  await page.getByLabel('Place of birth').fill('Delhi')
  await page.getByRole('button', { name: /New Delhi, Delhi, India/ }).click()
  await page.getByRole('button', { name: 'Check compatibility' }).click()
  await expect(page.locator('#match-score')).toContainText('/36')
  await expect(page.getByText('Graha Maitri')).toBeVisible()
})

test('Love & Marriage report from the Kundli', async ({ page }) => {
  await enterMyDetails(page)
  await page.getByRole('link', { name: 'Open my Love & Marriage report' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Zero')
  await expect(page.getByText('/100')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Love marriage or arranged?' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Shaadi alert' })).toBeVisible()
  // No horizontal scroll on phones.
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(0)
})

test('switching language translates the site', async ({ page, isMobile }) => {
  await page.goto('/')
  if (isMobile) await page.getByRole('button', { name: 'Menu' }).click()
  await page.getByLabel('Language').selectOption('ta')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('நீங்கள் பிறந்த வானத்தைத் தூனி பாபா படிக்கிறார்.')
  await expect(page.locator('html')).toHaveAttribute('lang', 'ta')
})

test('print / PDF view hides navigation and buttons', async ({ page }) => {
  await enterMyDetails(page)
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('button', { name: 'Share this reading' })).toBeHidden()
  await expect(page.getByText(/Generated by Dhuni Baba on/)).toBeVisible()
})
